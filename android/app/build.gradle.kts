/** Optional public deployment input, never a tracked domain/pin or an invitation. */
abstract class GenerateTrustedServerProfile : DefaultTask() {
    @get:InputFile
    @get:Optional
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val profile: RegularFileProperty
    @get:OutputDirectory
    abstract val assets: DirectoryProperty

    @TaskAction
    fun generate() {
        val output = assets.get().asFile
        output.deleteRecursively() // Omission must not accidentally package an older deployment.
        check(output.mkdirs()) { "Unable to create generated public assets" }
        if (!profile.isPresent) return
        val bytes = profile.get().asFile.inputStream().use { it.readNBytes(8193) }
        check(bytes.size <= 8192 && bytes.all { it.toInt() in 0..127 }) { "Invalid bounded public server profile" }
        val code = bytes.toString(Charsets.US_ASCII).filterNot { it == ' ' || it == '\t' || it == '\r' || it == '\n' }
        val prefix = "dmsg://server/"
        check(code.startsWith(prefix) && code.length <= 13 + (4096 * 4 + 2) / 3) { "Expected a bounded public server profile" }
        val payload = code.removePrefix(prefix)
        check(payload.isNotEmpty() && payload.all { it in 'A'..'Z' || it in 'a'..'z' || it in '0'..'9' || it == '-' || it == '_' }) {
            "Expected canonical public server profile encoding"
        }
        val decoded = try { Base64.getUrlDecoder().decode(payload) }
            catch (_: IllegalArgumentException) { throw GradleException("Invalid public server profile encoding") }
        check(decoded.size <= 4096 && Base64.getUrlEncoder().withoutPadding().encodeToString(decoded) == payload) {
            "Expected canonical bounded public server profile encoding"
        }
        output.resolve("server-profile.txt").writeText(code, Charsets.US_ASCII)
    }
}

val generateTrustedServerProfile = tasks.register<GenerateTrustedServerProfile>("generateTrustedServerProfile") {
    profile.set(layout.file(providers.gradleProperty("serverProfileFile").map { path ->
        val input = File(path)
        check(input.isAbsolute) { "serverProfileFile must be an absolute public-profile file path" }
        input
    }))
    assets.set(layout.buildDirectory.dir("generated/trustedServerProfile/assets"))
}

