// One file, not a Copy output-directory encompassing the entire repository.
abstract class Export53Apk : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apk: RegularFileProperty
    @get:OutputFile
    abstract val destination: RegularFileProperty
    @get:Input
    abstract val gateInstall: Property<Boolean>

    @TaskAction
    fun export() {
        check(!gateInstall.get()) {
            "53.apk is the main package; export without -PgateInstall=true"
        }
        apk.get().asFile.copyTo(destination.get().asFile, overwrite = true)
    }
}

// Installable development artifact, without changing the package/signing identity.
tasks.register<Export53Apk>("export53Apk") {
    dependsOn("assembleDebug")
    apk.set(layout.buildDirectory.file("outputs/apk/debug/app-debug.apk"))
    destination.set(rootProject.layout.projectDirectory.file("../53.apk"))
    gateInstall.set(providers.gradleProperty("gateInstall").map { it == "true" }.orElse(false))
}

